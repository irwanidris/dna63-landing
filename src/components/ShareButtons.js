/**
 * Share links shown at the end of an article. The links are plain intent
 * URLs, so they work without any third-party script; the native share and
 * copy buttons need the browser and only appear or work after hydration.
 */
export default function ShareButtons({ url, title }) {
  const [canShare, setCanShare] = useState(false);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    setCanShare(typeof navigator !== "undefined" && typeof navigator.share === "function");
  }, []);

  const u = encodeURIComponent(url);
  const t = encodeURIComponent(title);
  const tu = encodeURIComponent(`${title} ${url}`);

  const links = [
    ["WhatsApp", `https://wa.me/?text=${tu}`, "bg-[#25D366] text-white"],
    ["Facebook", `https://www.facebook.com/sharer/sharer.php?u=${u}`, "bg-[#1877F2] text-white"],
    ["Threads", `https://www.threads.net/intent/post?text=${tu}`, "bg-black text-white dark:bg-white dark:text-black"],
    ["X", `https://twitter.com/intent/tweet?url=${u}&text=${t}`, "bg-black text-white dark:bg-white dark:text-black"],
    ["Telegram", `https://t.me/share/url?url=${u}&text=${t}`, "bg-[#26A5E4] text-white"],
  ];

  const copyLink = async () => {
    try {
      await navigator.clipboard.writeText(url);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      window.prompt("Salin pautan ini:", url);
    }
  };

  const nativeShare = async () => {
    try {
      await navigator.share({ title, url });
    } catch {
      // Cancelled by the reader.
    }
  };

  const chip = "inline-flex items-center gap-2 px-4 py-2 rounded-xl text-sm font-bold hover:opacity-85 transition-opacity";

  return (
    <div className="mt-12 pt-8 border-t border-gray-100 dark:border-gray-800">
      <p className="text-xs font-black uppercase tracking-widest text-gray-400 mb-4">Kongsi artikel ini</p>
      <div className="flex flex-wrap gap-2">
        {canShare && (
          <button type="button" onClick={nativeShare} className={`${chip} bg-sabah-blue text-white`}>
            <StrokeIcon>
              <circle cx="18" cy="5" r="3" />
              <circle cx="6" cy="12" r="3" />
              <circle cx="18" cy="19" r="3" />
              <path d="M8.6 13.5l6.8 4M15.4 6.5l-6.8 4" />
            </StrokeIcon>
            Kongsi…
          </button>
        )}
        {links.map(([label, href, colors]) => (
          <a
            key={label}
            href={href}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={`Kongsi ke ${label}`}
            className={`${chip} ${colors}`}
          >
            <BrandIcon name={label} />
            {label}
          </a>
        ))}
        <button
          type="button"
          onClick={copyLink}
          className={`${chip} bg-gray-100 dark:bg-gray-800 text-gray-600 dark:text-gray-300`}
        >
          <StrokeIcon>
            {copied ? (
              <path d="M20 6L9 17l-5-5" />
            ) : (
              <>
                <path d="M10 13a5 5 0 0 0 7.5.5l3-3a5 5 0 0 0-7-7l-1.7 1.7" />
                <path d="M14 11a5 5 0 0 0-7.5-.5l-3 3a5 5 0 0 0 7 7l1.7-1.7" />
              </>
            )}
          </StrokeIcon>
          {copied ? "Pautan disalin" : "Salin pautan"}
        </button>
      </div>
    </div>
  );
}
